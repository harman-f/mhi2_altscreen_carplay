#!/usr/bin/env python3
"""Generate MibrProfileBinding.java for one profile and list its adapter source dirs.

One JAR is built per profile, so the profile is selected at compile time: the
generated class names the adapter implementing de.mibr.hmi.MibrOemProfile.
The adapter class and extra source directories come from
modules/profiles/<id>/hmi/oem-anchors.json.
"""
import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import prepare_oem_sources

CLASS_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$")
TEMPLATE = """package de.mibr.hmi;

/** Generated by generate_profile_binding.py; do not edit. */
final class MibrProfileBinding {
    static final String PROFILE_ID = "%(profile)s";
    static final String ADAPTER_CLASS = "%(adapter)s";

    private MibrProfileBinding() { }

    static MibrOemProfile create() {
        return new %(adapter)s();
    }
}
"""


def adapter_info(profile, profiles_dir=None):
    """Adapter class and adapter source dirs; both come from the profile's own file."""
    prepare_oem_sources.load_anchors(profile, profiles_dir)  # validates the name and chain
    base = Path(profiles_dir) if profiles_dir else prepare_oem_sources.PROFILES_DIR
    raw = json.loads((base / profile / "hmi" / "oem-anchors.json").read_text(encoding="utf-8"))
    adapter = raw.get("adapter_class", "")
    if not CLASS_RE.match(adapter):
        raise ValueError("ADAPTER_CLASS_INVALID=" + repr(adapter))
    dirs = [profile] + list(raw.get("adapter_from", []))
    return adapter, [d for d in dirs if (base / d / "hmi" / "java").is_dir()]


def render(profile, adapter):
    return TEMPLATE % {"profile": profile, "adapter": adapter}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", default=prepare_oem_sources.DEFAULT_PROFILE)
    parser.add_argument("--out-dir", type=Path, help="write de/mibr/hmi/MibrProfileBinding.java here")
    parser.add_argument("--print-source-dirs", action="store_true",
                        help="print the profile adapter java dirs (one per line)")
    args = parser.parse_args()
    try:
        adapter, dirs = adapter_info(args.profile)
        if args.print_source_dirs:
            for d in dirs:
                print(prepare_oem_sources.PROFILES_DIR / d / "hmi" / "java")
        if args.out_dir:
            target = args.out_dir / "de/mibr/hmi/MibrProfileBinding.java"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(render(args.profile, adapter), encoding="utf-8", newline="\n")
        return 0
    except ValueError as error:
        raise SystemExit(str(error))


if __name__ == "__main__":
    raise SystemExit(main())
