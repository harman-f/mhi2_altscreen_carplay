#!/usr/bin/env python3
"""Generate installer/config/profiles.list (and the README table) from profile.json.

--write regenerates, --check fails when the committed files differ. Host-only.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import check_profiles  # noqa: E402

LIST = "installer/config/profiles.list"
README = "modules/profiles/README.md"
BEGIN = "<!-- profiles-table:begin (generated by tools/release/generate_profiles_list.py) -->"
END = "<!-- profiles-table:end -->"


def render_list(profiles):
    lines = []
    for pid, d in profiles.items():
        s = d["selector"]
        lines.append("%s %s %s %d" % (s["digest"], pid, d["firmware_check"]["expected"] or "-",
                                      1 if s["install_enabled"] else 0))
    lines.sort()
    return ("# generated by tools/release/generate_profiles_list.py, do not edit\n"
            "# <sha256 of /ifs/lsd.jxe> <profile_id> <firmware_expected or -> <install_enabled 0|1>\n"
            + "\n".join(lines) + "\n")


def render_table(profiles):
    rows = ["| Profile | Firmware | `/ifs/lsd.jxe` SHA-256 | Evidence | Install enabled | API lsd.jar SHA-256 |",
            "| --- | --- | --- | --- | --- | --- |"]
    for pid, d in sorted(profiles.items()):
        s, h = d["selector"], d["hmi"]
        jar = "`%s` (%s)" % (h["api_jar_sha256"], h["api_jar_status"]) if h["api_jar_sha256"] else "to confirm"
        rows.append("| `%s` | `%s` | `%s` | %s | %s | %s |" % (
            pid, d["firmware"], s["digest"], s["evidence"], "yes" if s["install_enabled"] else "no", jar))
    return BEGIN + "\n" + "\n".join(rows) + "\n" + END


def apply_table(text, table):
    if BEGIN not in text or END not in text:
        raise SystemExit("README table markers missing")
    a, b = text.index(BEGIN), text.index(END) + len(END)
    return text[:a] + table + text[b:]


def expected_files(root=ROOT):
    profiles = check_profiles.load_profiles(root)
    errs = check_profiles.validate_all(profiles)
    if errs:
        raise SystemExit("\n".join(errs))
    readme = (Path(root) / README).read_text(encoding="utf-8")
    return {LIST: render_list(profiles), README: apply_table(readme, render_table(profiles))}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    bad = []
    for rel, want in expected_files().items():
        p = ROOT / rel
        if a.write:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(want, encoding="utf-8")
        elif not p.is_file() or p.read_text(encoding="utf-8") != want:
            bad.append(rel)
    if bad:
        raise SystemExit("PROFILES_LIST=STALE " + " ".join(bad))
    print("PROFILES_LIST=PASS")


if __name__ == "__main__":
    main()
